#!/usr/bin/env bash
# Writes test/coverage_all_files_test.dart, a test that imports every app library, so a coverage
# run counts files no test touches as 0% instead of leaving them out. Used by scripts/coverage.sh
# and by the `checks` job in CI; delete the file after the run.
set -euo pipefail
cd "$(dirname "$0")/.."

{
  echo "// Generated by scripts/write_coverage_helper.sh; imports every library so coverage includes it."
  echo "// ignore_for_file: unused_import, directives_ordering"
  git ls-files 'lib/*.dart' |
    grep -vE '\.(g|freezed|gr|config|gen)\.dart$|/app_localizations[^/]*\.dart$' |
    xargs grep -L '^part of' |
    sed "s|^lib/\(.*\)|import 'package:health_wallet/\1';|"
  echo "void main() {}"
} >test/coverage_all_files_test.dart
