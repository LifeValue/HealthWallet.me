#!/usr/bin/env bash
# Coverage status: runs the tests with coverage and prints the total, each feature area and the
# critical areas. A temporary test imports every app library, so files no test touches count as
# 0% instead of being left out of the numbers.
#   scripts/coverage.sh                  summary
#   scripts/coverage.sh --files <dir>    per-file lines for one directory (e.g. lib/features/sync/)
set -euo pipefail
cd "$(dirname "$0")/.."

helper=test/coverage_all_files_test.dart
trap 'rm -f "$helper"' EXIT
{
  echo "// Generated by scripts/coverage.sh; imports every library so coverage includes it."
  echo "// ignore_for_file: unused_import, directives_ordering"
  git ls-files 'lib/*.dart' |
    grep -vE '\.(g|freezed|gr|config|gen)\.dart$|/app_localizations[^/]*\.dart$' |
    xargs grep -L '^part of' |
    sed "s|^lib/\(.*\)|import 'package:health_wallet/\1';|"
  echo "void main() {}"
} >"$helper"

fvm flutter test --coverage --reporter=failures-only
fvm dart run tool/coverage_report.dart "$@"
