// Generates the Spanish, German and Romanian country names of the phone
// number picker from the Unicode CLDR territory names.
//
//   fvm dart run tool/generate_country_names.dart
//
// It downloads `main/<language>/territories.json` of the cldr-localenames-full
// package at the pinned [_cldrVersion] from the unicode-org/cldr-json
// repository into a fresh temporary directory, reads it as data only, and
// writes [_output] (then formats it). The English names stay the
// hand-written map in `country_names.dart`, so English is unchanged; its
// keys decide which countries get a name. To update the names, bump
// [_cldrVersion], run the script and review the diff.
import 'dart:convert';
import 'dart:io';

const _cldrVersion = '48.0.0';
const _languages = ['es', 'de', 'ro'];
const _patientUtils =
    'lib/features/user/presentation/preferences_modal/sections/patient/utils';
const _englishNames = '$_patientUtils/country_names.dart';
const _output = '$_patientUtils/country_names_cldr.dart';

String _url(String language) =>
    'https://raw.githubusercontent.com/unicode-org/cldr-json/$_cldrVersion/'
    'cldr-json/cldr-localenames-full/main/$language/territories.json';

Future<void> main() async {
  final isoCodes = RegExp(r'IsoCode\.([A-Z]{2}):')
      .allMatches(File(_englishNames).readAsStringSync())
      .map((m) => m.group(1)!)
      .toList();
  if (isoCodes.isEmpty) {
    stderr.writeln('No IsoCode keys found in $_englishNames');
    exitCode = 1;
    return;
  }

  final downloadDir = await Directory.systemTemp.createTemp('cldr_names_');
  final client = HttpClient();
  final names = <String, Map<String, String>>{};
  try {
    for (final language in _languages) {
      final file = File('${downloadDir.path}/$language.json');
      await _download(client, _url(language), file);
      final json =
          jsonDecode(await file.readAsString()) as Map<String, dynamic>;
      final territories =
          ((json['main'] as Map)[language]
                  as Map)['localeDisplayNames']['territories']
              as Map<String, dynamic>;
      names[language] = {
        for (final iso in isoCodes)
          if (territories[iso] is String) iso: territories[iso] as String,
      };
      final missing = isoCodes.where(
        (iso) => !names[language]!.containsKey(iso),
      );
      if (missing.isNotEmpty) {
        stdout.writeln('$language: no CLDR name for ${missing.join(', ')}');
      }
    }
  } finally {
    client.close();
    await downloadDir.delete(recursive: true);
  }

  File(_output).writeAsStringSync(_render(names));
  final format = await Process.run(Platform.resolvedExecutable, [
    'format',
    _output,
  ]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
  stdout.writeln('Wrote $_output from CLDR $_cldrVersion');
}

Future<void> _download(HttpClient client, String url, File target) async {
  final request = await client.getUrl(Uri.parse(url));
  final response = await request.close();
  if (response.statusCode != HttpStatus.ok) {
    throw HttpException('GET $url returned ${response.statusCode}');
  }
  await response.pipe(target.openWrite());
}

String _render(Map<String, Map<String, String>> names) {
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_country_names.dart from Unicode CLDR',
    )
    ..writeln(
      '// $_cldrVersion (cldr-localenames-full territory names). Do not edit by',
    )
    ..writeln(
      '// hand: run `fvm dart run tool/generate_country_names.dart` instead.',
    )
    ..writeln(
      "import 'package:phone_numbers_parser/phone_numbers_parser.dart';",
    )
    ..writeln()
    ..writeln(
      '/// Country names by language code, for the languages besides English.',
    )
    ..writeln('const Map<String, Map<IsoCode, String>> cldrCountryNames = {');
  for (final MapEntry(key: language, value: byIso) in names.entries) {
    out.writeln("  '$language': {");
    for (final MapEntry(key: iso, value: name) in byIso.entries) {
      out.writeln("    IsoCode.$iso: '${_escape(name)}',");
    }
    out.writeln('  },');
  }
  out.writeln('};');
  return out.toString();
}

String _escape(String s) =>
    s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');
